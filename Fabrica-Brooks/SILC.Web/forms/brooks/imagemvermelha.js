function question(pQuestion)
{
    if (document.getElementById(pQuestion).style.display == 'block')
    {
        document.getElementById(pQuestion).style.display = 'none';
    }
    else if (document.getElementById(pQuestion).style.display == 'none')
    {
        document.getElementById(pQuestion).style.display = 'block';
    }
}

function selecionar(pQuestion)
{
    document.getElementById(pQuestion).style.cursor = 'pointer';
    document.getElementById(pQuestion).style.fontWeight = 'bold';
}
function deselecionar(pQuestion)
{
    document.getElementById(pQuestion).style.cursor = 'hand';
    document.getElementById(pQuestion).style.fontWeight = 'normal';
}